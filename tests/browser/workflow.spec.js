import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { resolve } from "node:path";
import { readFile } from "node:fs/promises";

test("signed APK workflow, private reports, and responsive navigation", async ({page}) => {
  const email = randomUUID() + "@example.test";
  const password = "local-browser-" + randomUUID();
  await page.goto("/");
  await expect(page.getByRole("heading", {name:"Know what’s inside an Android app."})).toBeVisible();
  await page.keyboard.press("Tab");
  await expect(page.getByRole("link", {name:"Skip to content"})).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(page.locator("main")).toBeFocused();
  await page.getByRole("button", {name:"Create an account"}).click();
  await page.getByLabel("Email").fill(email);
  await page.getByLabel("Password").fill(password);
  await page.getByRole("button", {name:"Create account", exact:true}).click();
  await expect(page.getByRole("heading", {name:"Scan overview"})).toBeVisible();
  await expect(page.getByText("No scans match this view.")).toBeVisible();
  await page.getByRole("link", {name:"Scan an APK"}).click();
  await page.getByRole("button", {name:"Upload and scan"}).click();
  await expect(page.getByText("Choose a nonempty APK file.")).toBeVisible();
  const fixture = resolve(process.env.SENTINEL_TEST_FIXTURES || "data/fixtures", "original.apk");
  const chooserStart = page.waitForEvent("filechooser");
  await page.getByRole("button", {name:"Browse files"}).click();
  await (await chooserStart).setFiles(fixture);
  await expect(page.getByText(/original\.apk/)).toBeVisible();
  await page.getByRole("button", {name:"Upload and scan"}).click();
  await expect(page.getByRole("heading", {name:"Security findings"})).toBeVisible({timeout:55_000});
  await expect(page.getByRole("heading", {name:"Sensitive access requested", exact:true})).toBeVisible();
  await expect(page.getByText("Unverified identity", {exact:true})).toBeVisible();
  await expect(page.getByText("org.example.sentinel.fixture", {exact:true})).toBeVisible();
  const pdfStart = page.waitForEvent("download");
  await page.getByRole("link", {name:"PDF", exact:true}).click();
  const pdf = await pdfStart;
  const bytes = await readFile(await pdf.path());
  expect(bytes.subarray(0, 4).toString()).toBe("%PDF");
  const protectedReport = await page.getByRole("link", {name:"JSON", exact:true}).getAttribute("href");
  const jsonResponse = await page.request.get(protectedReport);
  expect((await jsonResponse.json()).signing.status).toBe("verified");
  await page.getByRole("link", {name:"Scan history"}).click();
  await page.getByLabel("Search APK").fill("sentinel.fixture");
  await page.getByRole("button", {name:"Apply filters"}).click();
  await expect(page.getByRole("link", {name:"org.example.sentinel.fixture"})).toBeVisible();

  await page.setViewportSize({width:390,height:844});
  const mobileMenu = page.getByRole("button", {name:"Navigation"});
  await expect(mobileMenu).toHaveAttribute("aria-expanded", "false");
  await mobileMenu.click();
  await expect(page.getByRole("navigation", {name:"Main navigation"})).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(mobileMenu).toBeFocused();
  await expect(mobileMenu).toHaveAttribute("aria-expanded", "false");
  await mobileMenu.click();
  await page.getByRole("link", {name:"Business calculator"}).click();
  await expect(page.getByRole("heading", {name:"Business calculator"})).toBeVisible();
  await expect(mobileMenu).toHaveAttribute("aria-expanded", "false");
  await page.getByLabel("Monthly active users").fill("50");
  await page.getByLabel("Paying customers", {exact:true}).fill("10");
  await page.getByLabel("Monthly revenue per paying customer").fill("20");
  await expect(page.getByText("$200.00", {exact:true}).first()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.getByRole("button", {name:"Sign out"}).click();
  await expect(page.getByRole("heading", {name:"Sign in", exact:true})).toBeVisible();
  expect((await page.request.get(protectedReport)).status()).toBe(401);
});

test("welcome screen keeps sign-in ahead of supporting content on a narrow phone", async ({page}) => {
  await page.setViewportSize({width:320,height:720});
  await page.goto("/");
  await expect(page.getByRole("heading", {name:"Know what’s inside an Android app."})).toBeVisible();
  const signIn = page.getByRole("button", {name:"Sign in", exact:true});
  await expect(signIn).toBeVisible();
  const capabilities = page.getByRole("heading", {name:"Signature verification"});
  const [signInBox, capabilitiesBox] = await Promise.all([signIn.boundingBox(), capabilities.boundingBox()]);
  expect(signInBox.y + signInBox.height).toBeLessThan(capabilitiesBox.y);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320);
});
